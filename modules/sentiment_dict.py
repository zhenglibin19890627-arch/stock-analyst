def get_sentiment_score(text):
    """
    基于金融关键词匹配，返回情绪得分。

    返回值: -1.0 ~ +1.0
      正数=利好倾向，负数=利空倾向，0=中性
    """
    if not text or not isinstance(text, str):
        return 0.0

    pos_weighted = 0
    neg_weighted = 0

    for word, weight in POSITIVE_WORDS.items():
        count = text.count(word)
        pos_weighted += count * weight

    for word, weight in NEGATIVE_WORDS.items():
        count = text.count(word)
        neg_weighted += count * weight

    total = pos_weighted + neg_weighted
    if total == 0:
        return 0.0

    # 加权差值 / 加权总和，范围 -1 ~ +1
    return (pos_weighted - neg_weighted) / total
