# ============================================================
# 四b、评级变更迟滞（021AG）
# ============================================================
# 背景：实测 67% 的评级变更间隔 ≤3 天、42% 的评级日分数距档位边界 ≤3 分——
# 分数在线附近抖动导致评级高频换挡，动态回测窗口被切碎（中位仅 5 天），
# 每次改评信号强度不足（动态准确率 46.6%，接近随机）。
# 规则：分数跨过档位边界还不够，必须再超出 MARGIN 分才真正换挡：
#   升档：score ≥ 目标档 min + MARGIN；
#   降档：score < 原档 min − MARGIN（多档跳变天然满足，崩盘不受迟滞拖延）。
# 效果：评级变"粘"，反应慢约半拍（边界附近），换挡即高置信信号。
# 回退：RATING_HYSTERESIS_ENABLED=False 即恢复旧行为（无需改其他代码）。
